"""Generate the Vocabulary Studio cask from verified stable release archives."""

import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile

REPO = "veryshyjelly/vocabulary-studio"
STABLE_TAG = r"v(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)"


def archive_names(tag):
    if not re.fullmatch(STABLE_TAG, tag):
        raise ValueError("expected a stable vX.Y.Z release tag")
    return [f"vocabulary-studio_{tag[1:]}_darwin_{arch}.zip"
            for arch in ("arm64", "amd64")]


def parse_checksums(text):
    checksums = {}
    for line in text.splitlines():
        if not line.strip():
            continue
        digest, name = line.split(maxsplit=1)
        name = name.lstrip(" *")
        if not re.fullmatch(r"[a-fA-F0-9]{64}", digest) or name in checksums:
            raise ValueError("invalid or duplicate checksum")
        checksums[name] = digest.lower()
    return checksums


def render(tag, checksums):
    arm, intel = archive_names(tag)
    for name in (arm, intel):
        if not re.fullmatch(r"[a-f0-9]{64}", checksums.get(name, "")):
            raise ValueError("missing or invalid checksum: " + name)
    return f'''# frozen_string_literal: true

# Generated by scripts/update_vocabulary_studio.py from verified release artifacts.
cask "vocabulary-studio" do
  arch arm: "arm64", intel: "amd64"

  version "{tag[1:]}"
  sha256 arm:   "{checksums[arm]}",
         intel: "{checksums[intel]}"

  url "https://github.com/{REPO}/releases/download/v#{{version}}/vocabulary-studio_#{{version}}_darwin_#{{arch}}.zip"
  name "Vocabulary Studio"
  desc "Desktop learning companion for Vocabulary.com"
  homepage "https://github.com/{REPO}"

  depends_on macos: ">= :ventura"

  app "Vocabulary Studio.app"

  uninstall quit: "com.veryshyjelly.vocabularystudio"

  zap trash: [
    "~/Library/Application Support/vocabulary_desktop",
    "~/Library/Preferences/com.veryshyjelly.vocabularystudio.plist",
    "~/Library/Saved Application State/com.veryshyjelly.vocabularystudio.savedState",
  ]

  caveats <<~EOS
    Vocabulary Studio is ad-hoc signed and is not notarized by Apple.
    If macOS blocks the first launch, attempt to open the app, then go to
    System Settings > Privacy & Security and choose Open Anyway.
  EOS
end
'''


def latest_release():
    try:
        result = subprocess.run(
            ["gh", "api", f"repos/{REPO}/releases/latest"],
            check=True, capture_output=True, text=True)
    except subprocess.CalledProcessError as error:
        if "(HTTP 404)" in error.stderr:
            print("No published Vocabulary Studio release yet; skipping cask update.")
            return None
        raise
    return json.loads(result.stdout)


def download(tag, name, directory):
    subprocess.run(
        ["gh", "release", "download", tag, "--repo", REPO,
         "--pattern", name, "--dir", str(directory)], check=True)


def update(target=None):
    release = latest_release()
    if release is None:
        return
    if release["draft"] or release["prerelease"]:
        raise ValueError("expected a published stable release")
    tag = release["tag_name"]
    names = archive_names(tag)
    assets = {asset["name"] for asset in release["assets"]}
    missing = {"checksums.txt", *names} - assets
    if missing:
        raise ValueError("release is missing " + ", ".join(sorted(missing)))

    with tempfile.TemporaryDirectory() as directory:
        directory = Path(directory)
        download(tag, "checksums.txt", directory)
        checksums = parse_checksums((directory / "checksums.txt").read_text())
        cask = render(tag, checksums)
        for name in names:
            download(tag, name, directory)
            with (directory / name).open("rb") as archive:
                digest = hashlib.file_digest(archive, "sha256").hexdigest()
            if digest != checksums[name]:
                raise ValueError("checksum mismatch: " + name)

    if target is None:
        target = Path(__file__).resolve().parent.parent / "Casks/vocabulary-studio.rb"
    target = Path(target)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(cask)
    print("Updated Vocabulary Studio cask to", tag)


if __name__ == "__main__":
    update()
