"""Update Eitri from a stable GitHub release, verifying downloaded artifacts."""
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile

REPO = 'veryshyjelly/eitri'


def render(tag, checksums):
    if not re.fullmatch(r'v(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)', tag):
        raise ValueError('expected a stable release tag')
    version = tag[1:]
    base = f'https://github.com/{REPO}/releases/download/{tag}/eitri_{version}_'
    platforms = [(os, arch) for os in ('darwin', 'linux') for arch in ('arm64', 'amd64')]
    binaries = [f'eitri_{version}_{os}_{arch}.tar.gz' for os, arch in platforms]
    available = [name in checksums for name in binaries]
    if any(available) and not all(available):
        raise ValueError('incomplete macOS/Linux binary release')
    lines = ['# Generated by scripts/update.py from verified release artifacts.',
             'class Eitri < Formula',
             '  desc "Competitive programming companion for the terminal"',
             '  homepage "https://eitri.veryshyjelly.in"',
             f'  version "{version}"', '  license "GPL-2.0-only"', '']
    if all(available):
        for os in ('darwin', 'linux'):
            lines.append('  on_' + ('macos' if os == 'darwin' else 'linux') + ' do')
            for arch, condition in [('arm64', 'arm'), ('amd64', 'intel')]:
                name = f'eitri_{version}_{os}_{arch}.tar.gz'
                lines += [f'    on_{condition} do', f'      url "{base}{os}_{arch}.tar.gz"',
                          f'      sha256 "{checksums[name]}"', '    end']
            lines += ['  end', '']
        install = ['    bin.install "eitri"']
    else:
        name = f'eitri_{version}_source.tar.gz'
        lines += [f'  url "{base}source.tar.gz"', f'  sha256 "{checksums[name]}"',
                  '', '  depends_on "go" => :build', '']
        install = ['    system "go", "build", *std_go_args(ldflags: "-s -w -X main.version=#{version}"), "."']
    lines += ['  def install', *install, '  end', '', '  test do',
              '    assert_equal "eitri version #{version}\\n", shell_output("#{bin}/eitri --version")',
              '  end', 'end', '']
    return '\n'.join(lines)


def update():
    release = json.loads(subprocess.check_output(
        ['gh', 'api', f'repos/{REPO}/releases/latest'], text=True))
    tag = release['tag_name']
    assets = {a['name'] for a in release['assets']}
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(['gh', 'release', 'download', tag, '--repo', REPO,
                        '--pattern', 'checksums.txt', '--dir', tmp], check=True)
        checksums = {}
        for line in (Path(tmp) / 'checksums.txt').read_text().splitlines():
            digest, name = line.split(maxsplit=1)
            name = name.lstrip(' *')
            if not re.fullmatch(r'[a-fA-F0-9]{64}', digest) or name in checksums:
                raise ValueError('invalid or duplicate checksum')
            checksums[name] = digest.lower()
        formula = render(tag, checksums)
        # Only download the artifacts used by this formula, never execute them.
        for url in re.findall(r'url "([^"]+)"', formula):
            name = url.rsplit('/', 1)[1]
            if name not in assets:
                raise ValueError('release is missing ' + name)
            subprocess.run(['gh', 'release', 'download', tag, '--repo', REPO,
                            '--pattern', name, '--dir', tmp], check=True)
            digest = hashlib.sha256((Path(tmp) / name).read_bytes()).hexdigest()
            if digest != checksums[name]:
                raise ValueError('checksum mismatch: ' + name)
        target = Path(__file__).resolve().parent.parent / 'Formula/eitri.rb'
        target.write_text(formula)
        print('Updated Eitri formula to', tag)


if __name__ == '__main__':
    update()
